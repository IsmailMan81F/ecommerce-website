/**
 * Returns the translated label for a given wilaya string or code
 */
export function formatWilaya(rawWilaya: string | undefined | null, lang: string = "en"): string {
  if (!rawWilaya) return "";

  const trimmed = rawWilaya.trim();
  const codeMatch = trimmed.match(/^(\d{2})/);
  const code = codeMatch ? codeMatch[1] : null;

  const found = code
    ? WILAYAS_DATA.find((w) => w.code === code)
    : WILAYAS_DATA.find((w) => trimmed.includes(w.fr) || trimmed.includes(w.en) || trimmed.includes(w.ar));

  if (!found) return rawWilaya;

  const normLang = lang.slice(0, 2).toLowerCase();
  if (normLang === "ar") return found.ar;
  if (normLang === "fr") return found.fr;
  return found.en;
}
