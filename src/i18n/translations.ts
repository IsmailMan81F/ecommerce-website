// Initialize i18next
const savedLanguage = (typeof localStorage !== "undefined" && localStorage.getItem("kord_language")) || "en";

i18n.use(initReactI18next).init({
  resources,
  lng: savedLanguage,
  fallbackLng: "en",
  interpolation: {
    escapeValue: false, // React already safe from XSS
  },
});

// Sync document dir and lang on language change
export function applyDocumentLanguage(lang: LanguageCode) {
  if (typeof document !== "undefined") {
    const isRtl = lang === "ar";
    document.documentElement.lang = lang;
    document.documentElement.dir = isRtl ? "rtl" : "ltr";
    if (isRtl) {
      document.body.classList.add("rtl");
      document.body.setAttribute("dir", "rtl");
    } else {
      document.body.classList.remove("rtl");
      document.body.setAttribute("dir", "ltr");
    }
  }
}

// Initial sync
applyDocumentLanguage(savedLanguage as LanguageCode);

i18n.on("languageChanged", (lng) => {
  if (typeof localStorage !== "undefined") {
    localStorage.setItem("kord_language", lng);
  }
  applyDocumentLanguage(lng as LanguageCode);
});

export default i18n;
